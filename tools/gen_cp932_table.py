#!/usr/bin/env python3
"""
Generate common/cp932_table.hpp — self-contained CP932 (Shift-JIS) <-> Unicode
lookup tables with zero dependency on <iconv.h> or Win32 NLS (required for
Android NDK Bionic and iOS builds, and guarantees deterministic transcoding
across all platforms).
"""

from __future__ import annotations

from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
OUT_PATH = ROOT_DIR / "common" / "cp932_table.hpp"


def build_tables() -> tuple[list[tuple[int, int]], list[tuple[int, int]]]:
    # Valid CP932 2-byte lead ranges: 0x81..0x9F (31) and 0xE0..0xFC (29) -> 60 leads
    # Valid trail ranges: 0x40..0x7E (63) and 0x80..0xFC (125) -> 188 trails
    # Total dense slots = 60 * 188 = 11,280 uint16_t entries (22.5 KB)
    sjis_to_uni: list[tuple[int, int]] = []
    uni_to_sjis_map: dict[int, int] = {}

    leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
    trails = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))

    for b0 in leads:
        for b1 in trails:
            raw = bytes([b0, b1])
            try:
                ch = raw.decode("cp932")
            except UnicodeDecodeError:
                continue
            if len(ch) != 1:
                continue
            cp = ord(ch)
            if cp > 0xFFFF:
                continue
            pair = (b0 << 8) | b1
            sjis_to_uni.append((pair, cp))
            # Prefer canonical encoding returned by Python's cp932 encoder
            if cp not in uni_to_sjis_map:
                try:
                    enc = ch.encode("cp932")
                    if len(enc) == 2:
                        uni_to_sjis_map[cp] = (enc[0] << 8) | enc[1]
                    else:
                        uni_to_sjis_map[cp] = pair
                except UnicodeEncodeError:
                    uni_to_sjis_map[cp] = pair

    # Ensure every round-trippable BMP codepoint encodes identically to Python cp932
    for cp in range(0x80, 0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if 0xFF61 <= cp <= 0xFF9F:
            continue  # handled directly as 1-byte halfwidth katakana
        try:
            enc = chr(cp).encode("cp932")
        except UnicodeEncodeError:
            continue
        if len(enc) == 2:
            uni_to_sjis_map[cp] = (enc[0] << 8) | enc[1]

    uni_to_sjis = sorted(uni_to_sjis_map.items())
    return sjis_to_uni, uni_to_sjis


def emit_header(sjis_to_uni: list[tuple[int, int]], uni_to_sjis: list[tuple[int, int]]) -> str:
    # Build dense decode table indexed by lead_idx (0..59) * 188 + trail_idx (0..187)
    dense = [0] * (60 * 188)
    for pair, cp in sjis_to_uni:
        b0 = (pair >> 8) & 0xFF
        b1 = pair & 0xFF
        li = (b0 - 0x81) if b0 <= 0x9F else (31 + (b0 - 0xE0))
        ti = (b1 - 0x40) if b1 <= 0x7E else (63 + (b1 - 0x80))
        dense[li * 188 + ti] = cp

    lines: list[str] = [
        "#pragma once",
        "// Auto-generated by tools/gen_cp932_table.py — DO NOT EDIT MANUALLY",
        "// Self-contained CP932 (Shift-JIS) <-> Unicode codec with zero iconv/Win32 dependency.",
        "",
        "#include <algorithm>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string>",
        "#include <vector>",
        "",
        "namespace rmexe::cp932 {",
        "",
        "inline bool is_lead_byte(uint8_t b) {",
        "    return (b >= 0x81u && b <= 0x9Fu) || (b >= 0xE0u && b <= 0xFCu);",
        "}",
        "",
        "inline bool is_trail_byte(uint8_t b) {",
        "    return (b >= 0x40u && b <= 0x7Eu) || (b >= 0x80u && b <= 0xFCu);",
        "}",
        "",
        "inline void append_utf8(std::string& out, uint32_t cp) {",
        "    if (cp < 0x80u) {",
        "        out.push_back(static_cast<char>(cp));",
        "    } else if (cp < 0x800u) {",
        "        out.push_back(static_cast<char>(0xC0u | (cp >> 6)));",
        "        out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));",
        "    } else if (cp < 0x10000u) {",
        "        out.push_back(static_cast<char>(0xE0u | (cp >> 12)));",
        "        out.push_back(static_cast<char>(0x80u | ((cp >> 6) & 0x3Fu)));",
        "        out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));",
        "    } else if (cp <= 0x10FFFFu) {",
        "        out.push_back(static_cast<char>(0xF0u | (cp >> 18)));",
        "        out.push_back(static_cast<char>(0x80u | ((cp >> 12) & 0x3Fu)));",
        "        out.push_back(static_cast<char>(0x80u | ((cp >> 6) & 0x3Fu)));",
        "        out.push_back(static_cast<char>(0x80u | (cp & 0x3Fu)));",
        "    }",
        "}",
        "",
        "// Dense 2-byte CP932 -> BMP Unicode table (60 leads x 188 trails = 11,280 entries)",
        "inline constexpr uint16_t kSjisToUni[60 * 188] = {",
    ]

    for i in range(0, len(dense), 16):
        chunk = ", ".join(f"0x{v:04X}u" for v in dense[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")
    lines.append("struct UniToSjisEntry {")
    lines.append("    uint16_t uni;")
    lines.append("    uint16_t sjis;")
    lines.append("};")
    lines.append("")
    lines.append(f"inline constexpr UniToSjisEntry kUniToSjis[{len(uni_to_sjis)}] = {{")
    for i in range(0, len(uni_to_sjis), 6):
        chunk = ", ".join(f"{{0x{u:04X}u, 0x{s:04X}u}}" for u, s in uni_to_sjis[i : i + 6])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")
    lines.extend(
        [
            "inline uint16_t decode_pair(uint8_t b0, uint8_t b1) {",
            "    if (!is_lead_byte(b0) || !is_trail_byte(b1)) return 0;",
            "    size_t li = (b0 <= 0x9Fu) ? static_cast<size_t>(b0 - 0x81u) : (31u + static_cast<size_t>(b0 - 0xE0u));",
            "    size_t ti = (b1 <= 0x7Eu) ? static_cast<size_t>(b1 - 0x40u) : (63u + static_cast<size_t>(b1 - 0x80u));",
            "    return kSjisToUni[li * 188u + ti];",
            "}",
            "",
            "inline bool encode_codepoint(uint32_t cp, uint8_t& b0, uint8_t& b1, int& out_len) {",
            "    if (cp < 0x80u) {",
            "        b0 = static_cast<uint8_t>(cp);",
            "        b1 = 0;",
            "        out_len = 1;",
            "        return true;",
            "    }",
            "    if (cp >= 0xFF61u && cp <= 0xFF9Fu) {",
            "        b0 = static_cast<uint8_t>(0xA1u + (cp - 0xFF61u));",
            "        b1 = 0;",
            "        out_len = 1;",
            "        return true;",
            "    }",
            "    if (cp > 0xFFFFu) return false;",
            "    uint16_t key = static_cast<uint16_t>(cp);",
            "    const UniToSjisEntry* begin = kUniToSjis;",
            "    const UniToSjisEntry* end = kUniToSjis + (sizeof(kUniToSjis) / sizeof(kUniToSjis[0]));",
            "    const UniToSjisEntry* it = std::lower_bound(",
            "        begin, end, key,",
            "        [](const UniToSjisEntry& e, uint16_t k) { return e.uni < k; }",
            "    );",
            "    if (it != end && it->uni == key) {",
            "        b0 = static_cast<uint8_t>((it->sjis >> 8) & 0xFFu);",
            "        b1 = static_cast<uint8_t>(it->sjis & 0xFFu);",
            "        out_len = 2;",
            "        return true;",
            "    }",
            "    return false;",
            "}",
            "",
            "inline std::string decode_to_utf8(const uint8_t* data, size_t len) {",
            "    if (!data || len == 0) return \"\";",
            "    size_t actual_len = 0;",
            "    while (actual_len < len && data[actual_len] != 0) {",
            "        ++actual_len;",
            "    }",
            "    if (actual_len == 0) return \"\";",
            "    std::string out;",
            "    out.reserve(actual_len * 2);",
            "    size_t i = 0;",
            "    while (i < actual_len) {",
            "        uint8_t b0 = data[i];",
            "        if (b0 < 0x80u) {",
            "            out.push_back(static_cast<char>(b0));",
            "            ++i;",
            "        } else if (b0 >= 0xA1u && b0 <= 0xDFu) {",
            "            append_utf8(out, 0xFF61u + static_cast<uint32_t>(b0 - 0xA1u));",
            "            ++i;",
            "        } else if (is_lead_byte(b0) && i + 1 < actual_len) {",
            "            uint16_t cp = decode_pair(b0, data[i + 1]);",
            "            if (cp != 0) {",
            "                append_utf8(out, cp);",
            "                i += 2;",
            "            } else {",
            "                ++i;",
            "            }",
            "        } else {",
            "            ++i;",
            "        }",
            "    }",
            "    return out;",
            "}",
            "",
            "inline std::vector<uint8_t> encode_from_utf8(const std::string& utf8) {",
            "    std::vector<uint8_t> out;",
            "    out.reserve(utf8.size());",
            "    size_t i = 0;",
            "    while (i < utf8.size()) {",
            "        uint32_t cp = 0;",
            "        uint8_t c = static_cast<uint8_t>(utf8[i]);",
            "        if (c < 0x80u) {",
            "            cp = c;",
            "            i += 1;",
            "        } else if ((c & 0xE0u) == 0xC0u && i + 1 < utf8.size()) {",
            "            cp = ((c & 0x1Fu) << 6) | (static_cast<uint8_t>(utf8[i + 1]) & 0x3Fu);",
            "            i += 2;",
            "        } else if ((c & 0xF0u) == 0xE0u && i + 2 < utf8.size()) {",
            "            cp = ((c & 0x0Fu) << 12) |",
            "                 ((static_cast<uint8_t>(utf8[i + 1]) & 0x3Fu) << 6) |",
            "                 (static_cast<uint8_t>(utf8[i + 2]) & 0x3Fu);",
            "            i += 3;",
            "        } else if ((c & 0xF8u) == 0xF0u && i + 3 < utf8.size()) {",
            "            cp = ((c & 0x07u) << 18) |",
            "                 ((static_cast<uint8_t>(utf8[i + 1]) & 0x3Fu) << 12) |",
            "                 ((static_cast<uint8_t>(utf8[i + 2]) & 0x3Fu) << 6) |",
            "                 (static_cast<uint8_t>(utf8[i + 3]) & 0x3Fu);",
            "            i += 4;",
            "        } else {",
            "            i += 1;",
            "            continue;",
            "        }",
            "        uint8_t b0 = 0, b1 = 0;",
            "        int clen = 0;",
            "        if (encode_codepoint(cp, b0, b1, clen)) {",
            "            out.push_back(b0);",
            "            if (clen == 2) out.push_back(b1);",
            "        }",
            "    }",
            "    return out;",
            "}",
            "",
            "} // namespace rmexe::cp932",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    sjis_to_uni, uni_to_sjis = build_tables()
    header = emit_header(sjis_to_uni, uni_to_sjis)
    OUT_PATH.write_text(header, encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({len(sjis_to_uni)} decode pairs, {len(uni_to_sjis)} encode pairs, {len(header):,} bytes)")


if __name__ == "__main__":
    main()
